const generated = new Map<string, string>();
const index = new Map<string, Set<string>>();
const banner = "<!-- Generated by npm run docs:generate. Edit src/content, not this file. -->";
const oneLine = (s: string) => s.replace(/\s*\n\s*/g, " ").trim();
const cell = (s: string) => oneLine(s).replace(/\|/g, "&#124;");
const label = (s: string) => oneLine(s).replace(/\[/g, "&#91;").replace(/\]/g, "&#93;");
const file = (w: WeekMeta) => `week-${String(w.number).padStart(2, "0")}.md`;
const anchor = (s: WeekSection) => `stage-${s.id}`;
const unique = (values: string[]) => [...new Set(values.filter(Boolean))];
const flatten = (blocks: Block[]): Block[] => blocks.flatMap(b => b.type === "callout" ? [b, ...flatten(b.blocks)] : [b]);

function topicsFor(blocks: Block[]): { title: string; blocks: Block[] }[] {
  const topics: { title: string; blocks: Block[] }[] = [];
  for (const b of blocks) {
    if (b.type === "heading") topics.push({ title: b.text, blocks: [] });
    else {
      if (!topics.length) topics.push({ title: "기본 개념과 문제 설정", blocks: [] });
      topics[topics.length - 1].blocks.push(b);
    }
  }
  return topics;
}

function blockText(b: Block): string {
  switch (b.type) {
    case "paragraph": case "heading": return b.text;
    case "callout": return b.title ?? "";
    case "list": return b.items.join("\n");
    case "table": return [...b.headers, ...b.rows.flat()].join("\n");
    default: return "";
  }
}

function terms(blocks: Block[]): string[] {
  return unique(flatten(blocks).flatMap(b => {
    const text = blockText(b);
    const bold = [...text.matchAll(/\*\*([^*]+)\*\*/g)].map(m => m[1]);
    // Explicit API names and comparison rows surface concepts without inventing new course topics.
    const code = [...text.matchAll(/`([^`\n]+)`/g)].map(m => `\`${m[1]}\``);
    const rows = b.type === "table" ? b.rows.map(r => r.find(v => v.trim()) ?? "") : [];
    return [...bold, ...code, ...rows].map(oneLine);
  }));
}

function source(w: WeekMeta, kind: "weeks" | "sections" | "labs" | "assignments", sectionId?: string): string {
  const name = `src/content/${kind}/week${w.number}.ts`;
  if (!sectionId) return `../../${name}`;
  const lines = fs.readFileSync(path.join(ROOT, name), "utf8").split(/\r?\n/);
  const n = lines.findIndex(line => kind === "weeks" ? line.includes(`{#${sectionId}}`) : line.includes(`"${sectionId}":`));
  if (n < 0) throw new Error(`Missing source: ${name}#${sectionId}`);
  return `../../${name}#L${n + 1}`;
}

function emit(name: string, lines: string[]) {
  generated.set(name, lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
}

function addTerms(w: WeekMeta, s: WeekSection, values: string[]) {
  const link = `[${w.number}.${s.order} ${label(s.title)}](${file(w)}#${anchor(s)})`;
  for (const raw of values) {
    const value = raw.replace(/\*\*/g, "").replace(/:$/, "").trim();
    if (!value) continue;
    const locations = index.get(value) ?? new Set<string>();
    locations.add(link);
    index.set(value, locations);
  }
}

